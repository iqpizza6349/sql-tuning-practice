SELECT
    e.employee_no
,   e.employee_name
,   e.position_code
,   s.base_salary
,   s.bonus
,   (s.base_salary + s.bonus) AS total_salary
FROM employee e
    ,salary s
WHERE e.status      = 'ACTIVE'
  and s.employee_key = e.employee_key
  and s.end_date IS NULL
;

