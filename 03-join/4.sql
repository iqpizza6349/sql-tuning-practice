SELECT
    e.employee_key
,   e.employee_name
,   e.position_code
,   s.base_salary
,   s.bonus
FROM DEPARTMENT d
    ,EMPLOYEE   e
    ,SALARY     s
WHERE d.department_key = 500
  AND e.department_key = d.department_key
  AND e.status         = 'ACTIVE'
  AND s.employee_key   = e.employee_key
  AND s.end_date is NULL
;

