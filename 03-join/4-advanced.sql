/*
 department_key 와 함께 status 에 대한 Index 가 추가되어
 Table Access Full 을 하지 않고 Employee 인덱스로 탐색하고 필요한 칼럼들의
 대해서는 BATCHED 로 처리하고 있음을 확인하고 있다. (테이블 접근)
 */

/*
 FBI(Function Based Index) 로 Unique Scan 을 유도할 수도 있다.
 위 실행 계획에서도 UK 를 사용했지만 Unique Scan 이 아닌 이유는 Index 에
 사용된 모든 칼럼을 사용하지 않은 부분이 클 것이다.
 */
SELECT
    e.employee_key
,   e.employee_name
,   e.position_code
,   s.base_salary
,   s.bonus
FROM DEPARTMENT d
    ,EMPLOYEE   e
    ,SALARY     s
WHERE d.department_key = 500
  AND e.department_key = d.department_key
  AND e.status         = 'ACTIVE'
  AND (CASE WHEN s.end_date IS NULL THEN s.employee_key END) = e.employee_key
;

