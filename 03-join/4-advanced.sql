/*
 4.sql 의 Employee Index 가 employee_key(PK) 아님
 (company_key, employee_no)(UK) 뿐이기에 Table Access Full 으로
 밖에 접근할 수 없어 인덱스를 추가한 버전.
 */

CREATE INDEX EMPLOYEE_IX_01
    ON EMPLOYEE(DEPARTMENT_KEY, STATUS)
    TABLESPACE TSD_COMPANY_IDX
;

SELECT
    e.employee_key
,   e.employee_name
,   e.position_code
,   s.base_salary
,   s.bonus
FROM DEPARTMENT d
    ,EMPLOYEE   e
    ,SALARY     s
WHERE d.department_key = 500
  AND e.department_key = d.department_key
  AND e.status         = 'ACTIVE'
  AND s.employee_key   = e.employee_key
  AND s.end_date is NULL
;

