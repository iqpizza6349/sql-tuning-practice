SELECT *
FROM (
    SELECT
        d.department_key
    ,   d.department_name
    ,   COUNT(e.employee_key) AS employee_count
    FROM department d
        ,employee   e
    WHERE d.company_key = 300
      AND e.department_key = d.department_key
      AND e.status      = 'ACTIVE'
    GROUP BY d.department_key, d.department_name
    ORDER BY employee_count desc, d.department_key
)
WHERE ROWNUM <= 3
;

