SELECT
    c.company_name, d.department_name, x.employee_count, x.avg_base_salary
FROM (
    SELECT *
    FROM (
        SELECT
            e.department_key
        ,   COUNT(*) AS employee_count
        ,   AVG(s.base_salary) AS avg_base_salary
        FROM employee   e
            ,salary     s
        WHERE e.status      = 'ACTIVE'
          AND s.employee_key= e.employee_key
          AND s.END_DATE IS NULL
        GROUP BY e.department_key
        HAVING COUNT(*) >= 20
        ORDER BY AVG(s.base_salary) DESC, e.department_key
    )
    WHERE ROWNUM <= 10
) x
, department d
, company c
WHERE d.department_key = x.department_key
  AND c.company_key = d.company_key
ORDER BY x.avg_base_salary DESC, x.department_key

