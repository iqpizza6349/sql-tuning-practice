SELECT
    c.company_key
,   c.company_name
,   COUNT(e.employee_key) AS employee_count
,   SUM(s.base_salary) AS total_base_salary
,   SUM(s.bonus) AS total_bonus
,   (SUM(s.base_salary) + SUM(s.bonus)) AS total_salary
FROM company    c
    ,employee   e
    ,salary     s
WHERE e.company_key = c.company_key
  AND e.status      = 'ACTIVE'
  AND (CASE WHEN s.end_date IS NULL THEN s.employee_key END)= e.employee_key
GROUP BY c.company_key, c.company_name
;

